/**
 * Версии контейнера sfnt, которые домен принимает: они несут ровно один шрифт —
 * TrueType-обводки (0x00010000), их старый макинтошевский вариант ("true") и CFF
 * ("OTTO"). Коллекции ("ttcf") здесь нет: шрифтов в ней несколько, а какой из них брать,
 * домен не решает (issue https://github.com/yuldashevsardor/telegram-bot/issues/181).
 *
 * Набор один на две разные проверки: `FontSignatureMatcher` сверяет по нему первые четыре
 * байта исходника под sfnt-расширением, `SfntReader` — версию перед разбором каталога
 * таблиц, и приходят к нему файлы, сигнатуру не проходившие (§7 architecture.md).
 * Проверки остаются разными, а составами расходиться им нельзя: версия, известная только
 * одной стороне, ломает не сборку, а поведение — файл либо доедет до кодека и упадёт там
 * `InvalidSfnt`, либо не пройдёт вход.
 */
export const SFNT_VERSIONS: ReadonlyArray<number> = [0x00010000, 0x74727565, 0x4f54544f];

/**
 * Версия как четыре байта головы файла: в контейнере она лежит big-endian.
 */
export function sfntVersionBytes(version: number): Array<number> {
    return [24, 16, 8, 0].map((shift) => (version >>> shift) & 0xff);
}
